import { describe, expect, it } from 'vitest';
import { debianServer } from '@tests/fixtures/machines';
import {
  installCrontab,
  parseAtTime,
  parseCrontab,
  readCrontab,
  removeCrontab,
  validateCrontab,
} from './cron';

/** 3 novembre 2026, 9 h 31 à Paris. */
const NOW = Date.UTC(2026, 10, 3, 8, 31, 44);

describe('tables cron', () => {
  it('accepte les planifications valides', () => {
    const text = [
      '# commentaire',
      'MAILTO=""',
      '30 2 * * 1-5 /usr/local/bin/sauvegarde.sh',
      '*/15 * * * * /bin/true',
      '0 8,12,18 1 jan,jul mon-fri echo x',
      '@reboot /usr/local/bin/demarrage.sh',
      '',
    ].join('\n');
    expect(validateCrontab(text)).toEqual([]);
    expect(parseCrontab(text)).toEqual([
      { schedule: '30 2 * * 1-5', command: '/usr/local/bin/sauvegarde.sh' },
      { schedule: '*/15 * * * *', command: '/bin/true' },
      { schedule: '0 8,12,18 1 jan,jul mon-fri', command: 'echo x' },
      { schedule: '@reboot', command: '/usr/local/bin/demarrage.sh' },
    ]);
  });

  it('signale le champ fautif, ligne par ligne', () => {
    expect(
      validateCrontab('61 * * * * x\n* 24 * * * x\n* * 0 * * x\n* * * 13 * x\n* * * * 8 x\n'),
    ).toEqual([
      { line: 1, message: 'bad minute' },
      { line: 2, message: 'bad hour' },
      { line: 3, message: 'bad day-of-month' },
      { line: 4, message: 'bad month' },
      { line: 5, message: 'bad day-of-week' },
    ]);
    expect(
      validateCrontab('* * * * *\n@sometimes x\n@daily\n5-2 * * * * x\n*/a * * * * x\n'),
    ).toEqual([
      { line: 1, message: 'bad command' },
      { line: 2, message: 'bad time specifier' },
      { line: 3, message: 'bad command' },
      { line: 4, message: 'bad minute' },
      { line: 5, message: 'bad minute' },
    ]);
  });

  it('installe la table dans le spool avec son en-tête, et la retire', () => {
    const machine = installCrontab(debianServer({}), 'hugo', '0 3 * * * /bin/true\n', '-', NOW);
    const node = machine.fs['/var/spool/cron/crontabs/hugo'];
    expect(node).toMatchObject({ owner: 'hugo', group: 'crontab', mode: 0o600 });
    expect(node?.type === 'file' && node.content).toMatch(/^# DO NOT EDIT THIS FILE/);
    expect(readCrontab(machine, 'hugo')).toBe('0 3 * * * /bin/true\n');
    expect(machine.crontabs['hugo']).toEqual([{ schedule: '0 3 * * *', command: '/bin/true' }]);
    const removed = removeCrontab(machine, 'hugo');
    expect(readCrontab(removed, 'hugo')).toBeNull();
    expect(removed.crontabs['hugo']).toBeUndefined();
  });
});

describe('heures de at', () => {
  it('lit les heures absolues et relatives, à l’heure de Paris', () => {
    expect(parseAtTime(['23:00'], NOW)).toBe(Date.UTC(2026, 10, 3, 22, 0));
    expect(parseAtTime(['2300'], NOW)).toBe(Date.UTC(2026, 10, 3, 22, 0));
    // Une heure déjà passée désigne le lendemain.
    expect(parseAtTime(['08:00'], NOW)).toBe(Date.UTC(2026, 10, 4, 7, 0));
    expect(parseAtTime(['now', '+', '30', 'minutes'], NOW)).toBe(Date.UTC(2026, 10, 3, 9, 1));
    expect(parseAtTime(['now', '+', '2', 'hours'], NOW)).toBe(Date.UTC(2026, 10, 3, 10, 31));
    expect(parseAtTime(['now', '+', '1', 'day'], NOW)).toBe(Date.UTC(2026, 10, 4, 8, 31));
    expect(parseAtTime(['now', '+', '1', 'week'], NOW)).toBe(Date.UTC(2026, 10, 10, 8, 31));
    expect(parseAtTime(['midnight'], NOW)).toBe(Date.UTC(2026, 10, 3, 23, 0));
    expect(parseAtTime(['noon'], NOW)).toBe(Date.UTC(2026, 10, 3, 11, 0));
    expect(parseAtTime(['teatime'], NOW)).toBe(Date.UTC(2026, 10, 3, 15, 0));
    expect(parseAtTime(['14:00', 'tomorrow'], NOW)).toBe(Date.UTC(2026, 10, 4, 13, 0));
    expect(parseAtTime(['tomorrow'], NOW)).toBe(Date.UTC(2026, 10, 4, 8, 31));
    expect(parseAtTime(['25:00'], NOW)).toBeNull();
    expect(parseAtTime(['quand', 'tu', 'veux'], NOW)).toBeNull();
  });
});
